"""Actual Chromium visual review at six CSS widths; no production deploy.

Executed inside GitHub Actions from the PR's working tree. The screenshots
capture the staged PlayerOne page, not a hand-drawn mockup or synthetic image.
"""
from __future__ import annotations
import asyncio
import functools
import http.server
import json
import os
import sys
import subprocess
from pathlib import Path
import threading

from playwright.async_api import async_playwright

ROOT=Path(__file__).resolve().parents[1]
WIDTHS=(320,375,390,768,1024,1440)
ARTIFACT=ROOT/"visual-review"
ARTIFACT.mkdir(exist_ok=True)


async def capture():
    # Preserve the exact same PNG generated by the production-bound renderer,
    # but using the exclusively fictional smoke-test fixture. NEVER post it.
    subprocess.run([sys.executable, "-c",
        'from src.discord_smoke import DEMO_MATCH; from src.recap_card import render_match_card; '
        'from pathlib import Path; Path("visual-review/discord-recap-v11-FICTIONAL.png").write_bytes('
        'render_match_card({**DEMO_MATCH, "winner": "Lonestar"}, demo=True))'],
        cwd=ROOT,check=True)
    handler=functools.partial(http.server.SimpleHTTPRequestHandler,directory=str(ROOT/"docs"))
    server=http.server.ThreadingHTTPServer(("127.0.0.1",0),handler)
    threading.Thread(target=server.serve_forever,daemon=True).start()
    origin=f"http://127.0.0.1:{server.server_port}"
    report={"origin":"staging checkout / Python static HTTP","screenshots":[]}
    try:
        async with async_playwright() as p:
            browser=await p.chromium.launch(headless=True,args=["--no-sandbox"])
            for width in WIDTHS:
                page=await browser.new_page(viewport={"width":width,"height":900},device_scale_factor=1)
                errors=[]
                page.on("pageerror",lambda error:errors.append(str(error)))
                await page.goto(origin+"/playerone-demo.html",wait_until="domcontentloaded",timeout=30000)
                await page.locator(".perf-svg").wait_for(timeout=20000)
                await page.locator(".snapshot-insight").first.wait_for(timeout=20000)
                await page.screenshot(path=str(ARTIFACT/f"playerone-{width}px.png"),
                                      full_page=True,animations="disabled")
                measurements=await page.evaluate("""() => ({
                   viewport:innerWidth,
                   root:document.documentElement.scrollWidth,
                   body:document.body.scrollWidth,
                   primaryCards:document.querySelectorAll('#profile-metrics .metric-tile').length,
                   secondaryCards:document.querySelectorAll('#profile-secondary .career-secondary-card').length,
                   donuts:document.querySelectorAll('#player-snapshot .profile-win-donut').length,
                   insights:document.querySelectorAll('#player-snapshot .snapshot-insight').length,
                   tabs:[...document.querySelectorAll('.perf-tab')].map(x=>x.textContent.trim()),
                   table:!!document.querySelector('.perf-details table')
                })""")
                report["screenshots"].append({"width":width,**measurements,"errors":errors})
                assert measurements["root"]<=width+2, f"Horizontal overflow at {width}px: {measurements}"
                assert measurements["primaryCards"]==4
                assert measurements["secondaryCards"]==3
                assert measurements["donuts"]==1
                assert measurements["insights"]==2
                assert len(measurements["tabs"])==5
                assert measurements["table"]
                assert not errors, f"JavaScript exceptions at {width}px: {errors}"
                # Exercise the actual redesigned five modes rather than only
                # checking that five tab labels exist.
                assert await page.locator('.perf-encoding-label').is_hidden()
                await page.locator('.perf-tab[data-metric="kills"]').click()
                assert await page.locator('.perf-encoding-label').is_visible()
                await page.locator('.perf-encoding').select_option('paired')
                assert await page.locator('.perf-paired-svg').count()==1
                if width in (390,1440):
                    await page.screenshot(path=str(ARTIFACT/f"playerone-paired-dots-{width}px.png"),
                                          full_page=True,animations="disabled")
                await page.locator('.perf-tab[data-metric="averages"]').click()
                assert await page.locator('.perf-encoding-label').is_hidden()
                assert await page.locator('.perf-table th').all_text_contents() == [
                    'Date','Map','Avg kills (5)','Avg deaths (5)','Kills','Deaths'
                ]
                await page.locator('.perf-window').select_option('20')
                assert await page.locator('.perf-table tbody tr').count()==20
                if width in (390,1440):
                    await page.screenshot(path=str(ARTIFACT/f"playerone-five-match-averages-{width}px.png"),
                                          full_page=True,animations="disabled")
                await page.close()
                # Also inspect the live WARCON-backed player lookup surface,
                # with no fake data injected into the browser or source files.
                real=await browser.new_page(viewport={"width":width,"height":900},device_scale_factor=1)
                real_errors=[]
                real.on("pageerror",lambda error:real_errors.append(str(error)))
                await real.goto(origin+"/players.html",wait_until="domcontentloaded",timeout=30000)
                await real.wait_for_timeout(1600)
                await real.screenshot(path=str(ARTIFACT/f"players-search-{width}px.png"),
                                      full_page=True,animations="disabled")
                real_overflow=await real.evaluate("document.documentElement.scrollWidth-innerWidth")
                assert real_overflow<=2, f"Search page horizontal overflow at {width}px: {real_overflow}"
                # When captured public data is present, exercise the entire
                # lookup → true profile → chart → saved match chain.
                usable=await real.evaluate("""() => {
                  try {return typeof publicState!=='undefined' &&
                    publicState.ready&&publicState.players.length>0} catch(_){return false}
                }""")
                if usable:
                    player_name=await real.evaluate("publicState.players[0].name")
                    await real.locator("#player-query").fill(player_name)
                    await real.locator("#player-search button[type='submit']").click()
                    if await real.locator("#player-candidates .candidate").count():
                        await real.locator("#player-candidates .candidate").first.click()
                    await real.locator("#dossier").wait_for(state="visible",timeout=15000)
                    await real.locator("#player-snapshot .profile-win-donut").wait_for(timeout=15000)
                    await real.screenshot(path=str(ARTIFACT/f"players-profile-{width}px.png"),
                                          full_page=True,animations="disabled")
                    actual=await real.evaluate("""() => ({
                      primary:document.querySelectorAll('#profile-metrics .metric-tile').length,
                      secondary:document.querySelectorAll('#profile-secondary .career-secondary-card').length,
                      donuts:document.querySelectorAll('#player-snapshot .profile-win-donut').length,
                      insights:document.querySelectorAll('#player-snapshot .snapshot-insight').length,
                      overflow:document.documentElement.scrollWidth-innerWidth,
                      share:!!document.querySelector('#share-player')
                    })""")
                    assert actual["primary"]==4 and actual["secondary"]==3
                    assert actual["donuts"]==1 and actual["insights"]==2 and actual["share"]
                    assert actual["overflow"]<=2, f"Live profile overflow {width}px: {actual}"
                    # Optional Tracker connection must appear only on genuine
                    # profiles, with no synthetic polygon or claimed login.
                    await real.locator("#progression-panel").wait_for(state="visible",timeout=10000)
                    assert await real.locator("#progression-role-radar").count()==1
                    assert await real.locator("#progression-role-radar [data-role-profile]").count()==0
                    assert "No 1ADAAR Steam ownership" in await real.locator("#progression-status").inner_text()
                    report.setdefault("realProfiles",[]).append({"width":width,**actual,
                        "progressionEmpty":True})
                assert not real_errors, f"Real player page errors at {width}: {real_errors}"
                await real.close()
                # Server-wide completed-match activity is source-backed and
                # must show a no-data notice (not fictional activity) until
                # completed WARCON matches are actually archived.
                activity=await browser.new_page(viewport={"width":width,"height":900},device_scale_factor=1)
                activity_errors=[]
                activity.on("pageerror",lambda error:activity_errors.append(str(error)))
                await activity.goto(origin+"/activity.html",wait_until="domcontentloaded",timeout=30000)
                await activity.locator("#act-season").wait_for(state="attached",timeout=10000)
                await activity.wait_for_function("() => !document.querySelector('#act-season').disabled",
                                                 timeout=10000)
                await activity.screenshot(path=str(ARTIFACT/f"recorded-activity-{width}px.png"),
                                          full_page=True,animations="disabled")
                result=await activity.evaluate("""() => ({
                    root:document.documentElement.scrollWidth,
                    width:innerWidth,
                    scope:document.querySelector('#act-season').value,
                    summary:document.querySelector('#act-status').textContent,
                    hasGrid:!!document.querySelector('.act-grid-table')
                })""")
                assert result["root"]<=width+2, f"Activity body overflow at {width}px: {result}"
                assert result["scope"]=="all"
                assert not result["hasGrid"],"A no-data archive must not render a fake heatmap"
                assert "No completed matches" in result["summary"]
                assert not activity_errors, f"Activity page Javascript errors at {width}: {activity_errors}"
                report.setdefault("serverActivity",[]).append({"width":width,**result})
                await activity.close()
                # Real home and map/team Pages routes must render at every width,
                # not merely their IA concept counterparts or the motion lab.
                for route,filename,required in [
                    ("index.html","home",["#server-status",".hero.motion-hero"]),
                    ("map-team.html","map-team",["#mt-message","#mt-kd-plot"])
                ]:
                    surface=await browser.new_page(viewport={"width":width,"height":900},
                                                   device_scale_factor=1)
                    surface_errors=[]
                    surface.on("pageerror",lambda error:surface_errors.append(str(error)))
                    await surface.goto(origin+"/"+route,wait_until="domcontentloaded",timeout=30000)
                    await surface.wait_for_timeout(450)
                    for required_selector in required:
                        # Map/Team detail panel is gated until real retained match data
                        # exists, so its DOM is present even when appropriately hidden.
                        assert await surface.locator(required_selector).count()>0, (
                            route,required_selector,width)
                    await surface.screenshot(
                        path=str(ARTIFACT/f"{filename}-{width}px.png"),
                        full_page=True,animations="disabled")
                    overflow=await surface.evaluate("document.documentElement.scrollWidth-innerWidth")
                    assert overflow<=2,f"{route} overflow at {width}px: {overflow}"
                    assert not surface_errors,f"{route} JS errors at {width}: {surface_errors}"
                    report.setdefault("sourceRoutes",[]).append({
                        "route":route,"width":width,"overflow":overflow,
                        "domReady":True,"jsErrors":surface_errors})
                    await surface.close()
                # Homepage laser/light sweep, isolated sample crown, and empty
                # production-bound podium are all reviewed at the same widths.
                motion=await browser.new_page(viewport={"width":width,"height":900},device_scale_factor=1)
                motion_errors=[]
                motion.on("pageerror",lambda error:motion_errors.append(str(error)))
                await motion.goto(origin+"/motion-review.html",wait_until="domcontentloaded",timeout=30000)
                await motion.locator(".hero-laser-trace").wait_for(timeout=15000)
                if width==1440:
                    # Preserve actual in-flight frames, not screenshots with
                    # animations disabled, so owner can inspect the requested sequence.
                    await motion.wait_for_timeout(800)
                    await motion.screenshot(path=str(ARTIFACT/"hero-laser-in-flight-1440px.png"),
                                            full_page=False)
                    await motion.wait_for_timeout(1900)
                    await motion.screenshot(path=str(ARTIFACT/"1ad-logo-sheen-in-flight-1440px.png"),
                                            full_page=False)
                    await motion.wait_for_timeout(500)
                else:
                    await motion.wait_for_timeout(3200)
                await motion.screenshot(path=str(ARTIFACT/f"motion-review-{width}px.png"),
                                        full_page=True,animations="disabled")
                motion_info=await motion.evaluate("""() => ({
                  width:innerWidth,root:document.documentElement.scrollWidth,
                  laser:getComputedStyle(document.querySelector('.hero-laser-trace')).animationName,
                  orbit:getComputedStyle(document.querySelector('.hero-logo-halo'),'::before').animationName,
                  crown:getComputedStyle(document.querySelector('#test-champion .weekly-crown')).display,
                  championSheen:getComputedStyle(document.querySelector('#test-champion .weekly-avatar'),'::before').animationName,
                  logo:document.querySelector('.hero-logo-halo img')?.getAttribute('src'),
                  logoLoaded:document.querySelector('.hero-logo-halo img')?.naturalWidth>0,
                  logoMask:getComputedStyle(document.querySelector('.hero-logo-halo'),'::after').maskImage,
                  logoMaskClip:getComputedStyle(document.querySelector('.hero-logo-halo'),'::after').clipPath,
                  glintWidth:parseFloat(getComputedStyle(document.querySelector('.hero-logo-halo'),'::after').width),
                  glintHeight:parseFloat(getComputedStyle(document.querySelector('.hero-logo-halo'),'::after').height),
                  imgWidth:document.querySelector('.hero-logo-halo img').getBoundingClientRect().width,
                  imgHeight:document.querySelector('.hero-logo-halo img').getBoundingClientRect().height,
                  rankBadgePosition:getComputedStyle(document.querySelector('#test-champion .weekly-rank')).position,
                  rankCentered:Math.abs(document.querySelector('#test-champion .weekly-rank').getBoundingClientRect().left+
                    document.querySelector('#test-champion .weekly-rank').getBoundingClientRect().width/2-
                    document.querySelector('#test-champion').getBoundingClientRect().left-
                    document.querySelector('#test-champion').getBoundingClientRect().width/2)<2,
                  crownClearOfRank:document.querySelector('#test-champion .weekly-rank').getBoundingClientRect().bottom+4 <=
                    document.querySelector('#test-champion .weekly-crown').getBoundingClientRect().top,
                  crownAboveAvatar:document.querySelector('#test-champion .weekly-crown').getBoundingClientRect().bottom <=
                    document.querySelector('#test-champion .weekly-avatar').getBoundingClientRect().top+2,
                  logoOpacity:Number(getComputedStyle(document.querySelector('.hero-graphic')).opacity),
                  logoTop:document.querySelector('.hero-logo-halo').getBoundingClientRect().top,
                  heroTextBottom:document.querySelector('.motion-hero .hero-text').getBoundingClientRect().bottom,
                  mainSource:document.querySelector('.lab-banner')?.textContent
                })""")
                assert motion_info["root"]<=width+2, f"Motion lab overflow {width}px: {motion_info}"
                assert "laser-outline-once" in motion_info["laser"]
                assert "logo-orbit-once" in motion_info["orbit"]
                assert motion_info["crown"]=="grid"
                assert "champion-avatar-orbit-once" in motion_info["championSheen"]
                assert motion_info["logo"]=="assets/1ad-logo.svg"
                assert motion_info["logoLoaded"],f"Official logo image failed to load at {width}px"
                assert "1ad-logo.svg" in motion_info["logoMask"],f"Metallic sheen is not masked to emblem at {width}px"
                assert motion_info["logoMaskClip"]=="none",f"Unexpected geometric clipping at {width}px"
                assert abs(motion_info["glintWidth"]-motion_info["imgWidth"])<1, \
                    f"Metal sweep width does not match SVG at {width}px: {motion_info}"
                assert abs(motion_info["glintHeight"]-motion_info["imgHeight"])<1, \
                    f"Metal sweep height does not match SVG at {width}px: {motion_info}"
                assert motion_info["rankBadgePosition"]=="static"
                assert motion_info["rankCentered"],f"First rank not centered at {width}px: {motion_info}"
                assert motion_info["crownClearOfRank"],f"1 and crown collide at {width}px: {motion_info}"
                assert motion_info["crownAboveAvatar"],f"Crown crosses avatar at {width}px: {motion_info}"
                if width<=720:
                    assert motion_info["logoOpacity"]>=.9, "Original 1AD emblem invisible on mobile"
                    assert motion_info["logoTop"]>=motion_info["heroTextBottom"]-2, \
                        f"Logo overlaps headline/copy at {width}px: {motion_info}"
                assert "STAGING-ONLY" in motion_info["mainSource"]
                # A replay button must restart BOTH the crown and its preceding
                # circular portrait highlight, not only the crown element.
                await motion.locator("#replay-crown").click()
                await motion.wait_for_timeout(130)
                restarted=await motion.evaluate("""() => {
                  const animations=[...document.querySelector('#test-champion').getAnimations({subtree:true})];
                  const time=name=>animations.filter(a=>a.animationName===name).map(a=>a.currentTime);
                  return {orbit:time('champion-avatar-orbit-once'),crown:time('weekly-crown-arrive')};
                }""")
                assert restarted["orbit"] and restarted["crown"],f"Champion replay missing animations: {restarted}"
                assert all(t is not None and t<500 for t in restarted["orbit"]+restarted["crown"]), \
                    f"Champion replay failed to reset its sheen or crown: {restarted}"
                await motion.goto(origin+"/weekly.html",wait_until="domcontentloaded",timeout=30000)
                await motion.wait_for_timeout(250)
                no_crown=await motion.evaluate("""() => ({
                  winner:document.querySelector('.weekly-podium-place.gold').getAttribute('data-award-verified'),
                  crown:getComputedStyle(document.querySelector('.weekly-podium-place.gold .weekly-crown')).display,
                  overflow:document.documentElement.scrollWidth-innerWidth
                })""")
                assert no_crown["winner"]=="false" and no_crown["crown"]=="none",no_crown
                assert no_crown["overflow"]<=2,no_crown
                await motion.screenshot(path=str(ARTIFACT/f"weekly-unawarded-{width}px.png"),
                                        full_page=True,animations="disabled")
                assert not motion_errors, f"Motion or weekly error at {width}: {motion_errors}"
                report.setdefault("motion",[]).append({"width":width,**motion_info,**no_crown})
                await motion.close()
            # Reduced-motion fallback and CSS-keyframe replay are checked in a
            # real browser; never require motion to read the actual content.
            reduced=await browser.new_page(viewport={"width":390,"height":844},device_scale_factor=1,
                                           reduced_motion="reduce")
            await reduced.goto(origin+"/motion-review.html",wait_until="domcontentloaded")
            reduced_styles=await reduced.evaluate("""() => ({
              laser:getComputedStyle(document.querySelector('.hero-laser-trace')).animationName,
              orbit:getComputedStyle(document.querySelector('.hero-logo-halo'),'::before').animationName,
              crown:getComputedStyle(document.querySelector('#test-champion .weekly-crown')).animationName,
              crownVisible:getComputedStyle(document.querySelector('#test-champion .weekly-crown')).display,
              championSheen:getComputedStyle(document.querySelector('#test-champion .weekly-avatar'),'::before').animationName
            })""")
            assert reduced_styles["laser"]=="none" and reduced_styles["orbit"]=="none",reduced_styles
            assert reduced_styles["crown"]=="none" and reduced_styles["crownVisible"]=="grid",reduced_styles
            assert reduced_styles["championSheen"]=="none",reduced_styles
            report["reducedMotion"]=reduced_styles
            await reduced.close()
            # Track keyboard accessibility with ordinary tab traversal on a narrow viewport.
            page=await browser.new_page(viewport={"width":390,"height":844})
            await page.goto(origin+"/playerone-demo.html",wait_until="domcontentloaded",timeout=30000)
            await page.keyboard.press("Tab")
            focus=await page.evaluate("document.activeElement?.tagName")
            report["firstKeyboardFocus"]=focus
            assert focus in ("A","BUTTON"),"First keyboard focus is not an actionable control"
            await page.close()
            await browser.close()
    finally:
        server.shutdown()
    (ARTIFACT/"report.json").write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,indent=2))


if __name__=="__main__":
    asyncio.run(capture())
